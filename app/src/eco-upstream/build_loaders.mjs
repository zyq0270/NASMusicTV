// 「生态地球」loader 打包脚本 —— 产出 app/src/main/assets/eco-globe/loaders.es5.js
//
// 用法（在 app/src/eco-upstream 下）：
//   npm install --no-save esbuild@0.24.0 three@0.160.0
//   node build_loaders.mjs
//   rm -rf node_modules package.json package-lock.json
//
// ⛔ 依赖必须装在本目录（构建输入），⛔ 绝不装进 assets/（会被 mergeAssets 打进 APK）。
//
// 设计要点（见 docs/archive/eco-globe-webview-plan.md §4.4）：
//  - r160 的 GLTFLoader / SkeletonUtils 只有 ESM 版，`module: None` 降级会保留 import 语句 ⇒ 走 bundle；
//  - three 本体（987 KB）已由 E41 的 assets/globe/three.es5.js 提供 ⇒ 别名到一个只读 window.THREE 的 shim，
//    ⛔ 不要把 three 再打进这个包；
//  - shim 的具名导出**从源码的 import 语句自动生成**（手抄漏一个 ⇒ undefined ⇒ 不报错但运行时静默出错）。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ENTRY = path.join(HERE, 'entry.mjs');
const SHIM = path.join(HERE, 'three-shim.mjs');
const OUT = path.join(HERE, '..', 'main', 'assets', 'eco-globe', 'loaders.es5.js');

// ⚠️ 目标档位：方案 §4.4 原写 `--target=es5`，实测 **esbuild 0.24.0 无法降到 ES5**
// （`Transforming class syntax / const / let to "es5" is not supported yet`，892 条）。
// 这正是方案 §九 R1 预告的退路：**改 es2015**。电视端反正黑屏（宿主问题，§10.215）
// ⇒ 放弃 Chrome 39 兼容零损失；手机端 WebView 均 >= Chrome 60。
const TARGET = 'es2015';

const LOADER_FILES = [
  path.join(HERE, 'node_modules', 'three', 'examples', 'jsm', 'loaders', 'GLTFLoader.js'),
  path.join(HERE, 'node_modules', 'three', 'examples', 'jsm', 'utils', 'SkeletonUtils.js')
];

for (const f of LOADER_FILES) {
  if (!fs.existsSync(f)) {
    console.error(`✗ 缺少 ${path.relative(HERE, f)} —— 先跑 npm install --no-save esbuild@0.24.0 three@0.160.0`);
    process.exit(1);
  }
}

// ── 1. 递归收集所有可达源文件里 `import { … } from 'three'` 的具名导入 ────────────────
function collectThreeNames(roots) {
  const names = new Set();
  const seen = new Set();
  const queue = [...roots];
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    if (!fs.existsSync(file)) continue;
    const src = fs.readFileSync(file, 'utf8');

    // `import * as NS from 'three'` 在 shim 形态下语义不等价 ⇒ 直接报错，别静默错
    if (/import\s+\*\s+as\s+\w+\s+from\s*['"]three['"]/.test(src)) {
      console.error(`✗ ${path.relative(HERE, file)} 使用 \`import * as … from 'three'\`，shim 不支持；请改打包入口`);
      process.exit(1);
    }

    for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g)) {
      const body = m[1];
      const spec = m[2];
      if (spec === 'three') {
        for (const part of body.split(',')) {
          // 支持 `a as b`：shim 只要提供原名 `a`
          const name = part.trim().split(/\s+as\s+/)[0].trim();
          if (name) names.add(name);
        }
      } else if (spec.startsWith('.')) {
        queue.push(path.resolve(path.dirname(file), spec));
      }
    }
  }
  return [...names].sort();
}

const names = collectThreeNames(LOADER_FILES);
if (names.length === 0) {
  console.error('✗ 没从源码里收集到任何 three 具名导入 —— 解析规则失效了？');
  process.exit(1);
}

// ── 2. 生成 shim（每次覆盖写，⛔ 不要手工编辑 three-shim.mjs） ──────────────────────
const shim = [
  '// AUTO-GENERATED by build_loaders.mjs —— 不要手工编辑。',
  '// 只读 E41 的 window.THREE，⛔ 不打包 three 本体（省 ~987 KB）。',
  'var T = (typeof window !== \'undefined\' ? window : globalThis).THREE;',
  'if (!T) { throw new Error(\'loaders.es5.js 需要先加载 three.es5.js（window.THREE 未定义）\'); }',
  'export default T;',
  ...names.map((n) => `export var ${n} = T.${n};`),
  ''
].join('\n');
fs.writeFileSync(SHIM, shim, 'utf8');
console.log(`✓ three-shim.mjs：${names.length} 个具名导出`);

// ── 3. 打包 ──────────────────────────────────────────────────────────────────────
fs.mkdirSync(path.dirname(OUT), { recursive: true });

const threeAliasPlugin = {
  name: 'three-shim-alias',
  setup(build) {
    build.onResolve({ filter: /^three$/ }, () => ({ path: SHIM }));
  }
};

try {
  await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUT,
    bundle: true,
    format: 'iife',
    target: TARGET,
    platform: 'browser',
    legalComments: 'none',
    charset: 'utf8',
    plugins: [threeAliasPlugin],
    logLevel: 'info'
  });
} catch (e) {
  console.error('✗ esbuild 失败。若报 "Transforming … to the configured target environment is not supported"');
  console.error('  ⇒ 目标改 es2015（电视端反正黑屏，见方案 §九 R1）。原始错误：');
  throw e;
}

const size = fs.statSync(OUT).size;
const out = fs.readFileSync(OUT, 'utf8');
console.log(`✓ ${path.relative(HERE, OUT)} —— ${size} B`);
if (!/\bGLTFLoader\b/.test(out) || !/\bSkeletonUtils\b/.test(out)) {
  console.error('✗ 产物里找不到 GLTFLoader / SkeletonUtils 赋值 —— 检查 entry.mjs');
  process.exit(1);
}
