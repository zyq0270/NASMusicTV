#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""E55「街机合集」：把**上游原件**打包成运行时图集 + 帧表（⛔ 不手改生成物）。

⚠️ 效果编号是 **E55**（`"54"` 归 `ECO_GLOBE`「生态地球」），但**文件名与路径仍带 `e54_` 前缀**
   （`scripts/e54_pack_sprites.py`、`app/src/e54-upstream/`、`app/src/main/assets/e54_arcade/`）：
   那是脚本 ↔ 文档 ↔ 产物的既有契约 ⇒ **效果编号改 E55，文件名不动**。

来源（全部在 `app/src/e54-upstream/`，该目录已 .gitignore，⛔ 绝不能进公开仓库）：

  · 精灵 232 张 PNG —— `vermiceli/nes-contra-us` 的 `docs/sprite_library/contra_sprites/`，
    NES ROM 提取图，文件名与 `bank1.asm` 的 `sprite_ptr_tbl_0/1` 标签一致。
  · 瓦片 256 块 8×8 —— `MikeWuPing/UEFI_Contra` 的 `src/tiles_c.h`
    （`gNesTiles[256][64]`，每块 64 个 0x00RRGGBB，level 1 pattern table，同样是 ROM 提取）。

产物（**会进 APK**；v2.39.18 起随公开包分发 —— 上游原件仍 ⛔ 不入仓）：

  · `app/src/main/assets/e54_arcade/contra_atlas.png` —— 1024×1024 RGBA，最近邻采样专用
  · `app/src/main/java/.../render/ContraSpriteFrames.kt` —— 帧名 → (x,y,w,h) 表
  · 图集底部预留 40 px 给 `ArcadeAtlas` 画 HUD 文字帧（起始 y 写进生成物）

⚠️ 依赖 Pillow（本机 `python -m pip install pillow`）。生成物与上游原件必须**逐字节可复算**：
   上游原件一变就重跑本脚本；⛔ 不许手工改 atlas.png / ContraSpriteFrames.kt。

用法：仓库根 `python scripts/e54_pack_sprites.py`
"""
from __future__ import print_function

import io
import os
import re
import sys

try:
    from PIL import Image, ImageChops
except ImportError:
    sys.exit('需要 Pillow：python -m pip install pillow')

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
UP = os.path.join(ROOT, 'app', 'src', 'e54-upstream')
SPRITES = os.path.join(UP, 'nes-contra-us', 'docs', 'sprite_library', 'contra_sprites')
TILES_H = os.path.join(UP, 'uefi_contra', 'src', 'tiles_c.h')
OUT_PNG = os.path.join(ROOT, 'app', 'src', 'main', 'assets', 'e54_arcade', 'contra_atlas.png')
OUT_KT = os.path.join(
    ROOT, 'app', 'src', 'main', 'java', 'com', 'nasmusic', 'tv',
    'visualizer', 'arcade', 'render', 'ContraSpriteFrames.kt',
)

SIZE = 1024
PAD = 2                 # 帧间留白，GL_NEAREST 下防串色
TEXT_RESERVE = 40       # 底部留给 HUD 文字帧
TILE_COUNT = 256
TILE_PX = 8


def load_sprites():
    out = []
    for name in sorted(os.listdir(SPRITES)):
        if not name.lower().endswith('.png'):
            continue
        im = Image.open(os.path.join(SPRITES, name)).convert('RGBA')
        stem = name[:-4]
        # ⛔ 原件本来就多叫 `sprite_02.png` —— 再加前缀会变成 `sprite_sprite_02`，
        #    而 ContraArt 按上游标签写的是 `sprite_02` ⇒ 全场景取不到帧（白画面）。
        #    只有 4 张奖牌/GameOver 不带前缀，统一补成 `sprite_` 便于门禁分类。
        key = stem if stem.startswith('sprite_') else 'sprite_' + stem
        out.append((key, im))
    return out


def load_tiles():
    text = io.open(TILES_H, encoding='utf-8', errors='replace').read()
    nums = re.findall(r'0x([0-9A-Fa-f]{8})', text)
    need = TILE_COUNT * TILE_PX * TILE_PX
    if len(nums) < need:
        raise SystemExit('tiles_c.h 颜色数不足：%d < %d' % (len(nums), need))
    vals = [int(x, 16) for x in nums[:need]]
    out = []
    for idx in range(TILE_COUNT):
        chunk = vals[idx * 64:(idx + 1) * 64]
        im = Image.new('RGBA', (TILE_PX, TILE_PX))
        # 0x00000000 = NES 背景色 ⇒ 地形瓦片必须是**不透明黑**（否则会漏出天空）
        im.putdata([
            ((v >> 16) & 255, (v >> 8) & 255, v & 255, 255)
            for v in chunk
        ])
        out.append(('tile_%02x' % idx, im))
    return out


def pack(frames):
    """整行式打包；返回 (bitmap, rects, text_start_y)。"""
    bmp = Image.new('RGBA', (SIZE, SIZE), (0, 0, 0, 0))
    rects = []
    x = y = row_h = 0
    for name, im in frames:
        w, h = im.size
        if x + w + PAD > SIZE:
            x = 0
            y += row_h + PAD
            row_h = 0
        if y + h + PAD > SIZE - TEXT_RESERVE:
            raise SystemExit('图集装不下：%s %dx%d 时 y=%d' % (name, w, h, y))
        bmp.alpha_composite(im, (x, y))
        rects.append((name, x, y, w, h))
        x += w + PAD
        row_h = max(row_h, h)
    text_y = y + row_h + PAD
    if text_y > SIZE - TEXT_RESERVE:
        raise SystemExit('文字区不足：text_y=%d' % text_y)
    # 白块帧放**右下角**：文字帧从 TEXT_START_Y 起横向铺，永远不会碰到这里
    for dy in range(2):
        for dx in range(2):
            bmp.putpixel((SIZE - 4 + dx, SIZE - 4 + dy), (255, 255, 255, 255))
    rects.append(('white', SIZE - 4, SIZE - 4, 2, 2))
    return bmp, rects, text_y


def emit_kotlin(rects, text_y, sprite_n, tile_n):
    rows = ['%s,%d,%d,%d,%d' % (n, x, y, w, h) for (n, x, y, w, h) in rects]
    table = ';'.join(rows)
    kt = '''package com.nasmusic.tv.visualizer.arcade.render

// GENERATED by scripts/e54_pack_sprites.py —— ⛔ 不要手工改，改上游原件后重跑脚本。
// 上游：vermiceli/nes-contra-us 的 ROM 提取精灵 + MikeWuPing/UEFI_Contra 的 level 1 pattern table。
// ⚠️ 这些是 ROM 提取素材，版权归原始权利人所有 ⇒ 仅存在于私有分支，⛔ 绝不进公开包。

/**
 * 上游精灵 / 瓦片图集的帧表（与 `assets/e54_arcade/contra_atlas.png` 一一对应）。
 *
 * 共 %d 帧：%d 张精灵 + %d 块 8×8 瓦片 + 1 个白块。
 * 表在首次访问时解析一次（**绘制路径零分配**：运行时只查 [rect]）。
 */
object ContraSpriteFrames {

    /** 图集边长（GLES2 保证 ≥ 2048，1024 安全） */
    const val SIZE = %d

    /** `ArcadeAtlas` 画 HUD 文字帧的起始 y（图集底部预留区） */
    const val TEXT_START_Y = %d

    /** 精灵帧数（用于门禁自证「全部都拿过来了」） */
    const val SPRITE_COUNT = %d

    /** 瓦片帧数 */
    const val TILE_COUNT = %d

    /** 一行 = `name,x,y,w,h`；分号分隔。⛔ 顺序即打包顺序，不要重排。 */
    private const val TABLE = "%s"

    class Rect(val x: Int, val y: Int, val w: Int, val h: Int)

    private val index: Map<String, Rect> by lazy {
        val m = HashMap<String, Rect>(TABLE.length / 16)
        // 拆分只发生在首次访问（初始化期），绘制路径只读 [rect]
        for (row in TABLE.split(';')) {
            val p = row.split(',')
            m[p[0]] = Rect(p[1].toInt(), p[2].toInt(), p[3].toInt(), p[4].toInt())
        }
        m
    }

    fun rect(name: String): Rect? = index[name]

    fun names(): Set<String> = index.keys

    fun count(): Int = index.size
}
''' % (len(rects), sprite_n, tile_n, SIZE, text_y, sprite_n, tile_n, table)
    io.open(OUT_KT, 'w', encoding='utf-8', newline='\n').write(kt)


def main():
    sprites = load_sprites()
    tiles = load_tiles()
    if len(sprites) != 232:
        print('⚠️ 精灵数 %d ≠ 232（上游版本可能变了，请核对）' % len(sprites))
    if len(tiles) != TILE_COUNT:
        raise SystemExit('瓦片数不对：%d' % len(tiles))
    frames = sprites + tiles
    area = sum(im.width * im.height for _, im in frames)
    print('上游原件：%d 张精灵 + %d 块瓦片，像素合计 %d（图集容量 %d）'
          % (len(sprites), len(tiles), area, SIZE * (SIZE - TEXT_RESERVE)))

    bmp, rects, text_y = pack(frames)
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    bmp.save(OUT_PNG, 'PNG', optimize=True)
    emit_kotlin(rects, text_y, len(sprites), len(tiles))

    print('已生成 %s (%d B)' % (os.path.relpath(OUT_PNG, ROOT), os.path.getsize(OUT_PNG)))
    print('已生成 %s (%d 帧, 文字起始 y=%d)' % (os.path.relpath(OUT_KT, ROOT), len(rects), text_y))
    # 自检
    # 自检 1：逐像素对账（帧名/坐标错位 ⇒ 场上取到别人的图，肉眼极难发现）
    by_name = {n: (x, y, w, h) for (n, x, y, w, h) in rects}
    for name, im in frames:
        x, y, w, h = by_name[name]
        crop = bmp.crop((x, y, x + w, y + h))
        if ImageChops.difference(im, crop).getbbox() is not None:
            raise SystemExit('像素对账失败：%s 在图集里与原件不一致' % name)

    # 自检 2：渲染层 ContraArt 引用的每个帧名都必须真实存在
    # （2026-11-10 踩过：给原件文件名又加了一层 sprite_ 前缀 ⇒ 全场景取不到帧）
    art_path = os.path.join(
        ROOT, 'app', 'src', 'main', 'java', 'com', 'nasmusic', 'tv',
        'visualizer', 'arcade', 'render', 'ContraArt.kt',
    )
    art = io.open(art_path, encoding='utf-8').read()
    refs = set(re.findall(r'"((?:sprite|tile)_[0-9a-f]{2})"', art))
    if len(refs) < 20:
        raise SystemExit('ContraArt 帧名扫描为空（正则失配 = 门禁空转）')
    missing = sorted(refs - set(by_name))
    if missing:
        raise SystemExit('ContraArt 引用了图集里不存在的帧：%s' % missing)

    # 自检 3：素材打包区不越界
    used = max(y + h for (n, _, y, _, h) in rects if n != 'white')
    assert used <= SIZE - TEXT_RESERVE, '打包越界'
    assert len({n for n, _, _, _, _ in rects}) == len(rects), '帧名重复'
    print('自检通过：逐像素 %d 帧一致 / ContraArt %d 个引用全部命中 / 最高占用 y=%d'
          % (len(frames), len(refs), used))


if __name__ == '__main__':
    main()
